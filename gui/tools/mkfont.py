#!/usr/bin/env python3
"""Render a monospace TTF into a 1-bit C bitmap font (ASCII 32..126).

Usage: mkfont.py FONT.ttf SIZE > font.h
Each glyph row is a uint16_t, bit 15 = leftmost pixel.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path, size = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, size)
ascent, descent = font.getmetrics()
cw = max(font.getbbox(chr(c))[2] for c in range(32, 127))
cw = min(cw, 16)
ch = ascent + descent

rows = []
for c in range(32, 127):
    im = Image.new("1", (cw, ch), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=1)
    px = im.load()
    glyph = []
    for y in range(ch):
        v = 0
        for x in range(cw):
            if px[x, y]:
                v |= 1 << (15 - x)
        glyph.append(v)
    rows.append(glyph)

print("/* generated by tools/mkfont.py from %s @ %dpx */" % (path.split("/")[-1], size))
print("#define FONT_W %d" % cw)
print("#define FONT_H %d" % ch)
print("static const unsigned short font_bits[95][FONT_H] = {")
for c, g in zip(range(32, 127), rows):
    print("  {" + ",".join("0x%04x" % v for v in g) + "}, /* %r */" % chr(c))
print("};")
